    /// Classic marching-cubes surface extraction for a binary voxel field. Each
    /// cell is the cube whose 8 corners are voxel samples at (x..x+1, y..y+1,
    /// z..z+1); a corner counts as "inside" when the byte matches `targetValue`.
    ///
    /// The output mesh has its vertices placed in unit-cube-local space:
    /// voxel (i, j, k) maps to position ((i / (W-1)) - 0.5, (j / (H-1)) - 0.5,
    /// (k / (D-1)) - 0.5), so attaching the mesh to the VolumeRenderer's cube
    /// transform makes it line up with the volumetric texture sample.
    ///
    /// Used by MedicalVizWorkstation to render each Segment as a solid coloured
    /// surface (ITK-SNAP-style) instead of relying on volumetric mask compositing.
    public static class MarchingCubes
    {
        public static Mesh Build(byte[] field, int W, int H, int D, byte targetValue)
        {
            var verts = new List<Vector3>();
            var tris = new List<int>();
            // Edge-cache: for each cell-(x,y,z) we may emit up to 3 unique
            // vertices (one per "primary" edge); we cache them in a sparse
            // dictionary so neighbouring cells reuse the same vertex index.
            var cache = new Dictionary<long, int>(1 << 14);

            float invW = 1f / Mathf.Max(1, W - 1);
            float invH = 1f / Mathf.Max(1, H - 1);
            float invD = 1f / Mathf.Max(1, D - 1);

            for (int z = 0; z < D - 1; z++)
            for (int y = 0; y < H - 1; y++)
            for (int x = 0; x < W - 1; x++)
            {
                // Build the 8-bit cube index — which of the 8 corners are inside.
                int idx = 0;
                if (field[Index(x,     y,     z,     W, H)] == targetValue) idx |= 1;
                if (field[Index(x + 1, y,     z,     W, H)] == targetValue) idx |= 2;
                if (field[Index(x + 1, y + 1, z,     W, H)] == targetValue) idx |= 4;
                if (field[Index(x,     y + 1, z,     W, H)] == targetValue) idx |= 8;
                if (field[Index(x,     y,     z + 1, W, H)] == targetValue) idx |= 16;
                if (field[Index(x + 1, y,     z + 1, W, H)] == targetValue) idx |= 32;
                if (field[Index(x + 1, y + 1, z + 1, W, H)] == targetValue) idx |= 64;
                if (field[Index(x,     y + 1, z + 1, W, H)] == targetValue) idx |= 128;
                if (idx == 0 || idx == 255) continue;

                int edgeMask = EdgeTable[idx];
                Span<int> edgeVerts = stackalloc int[12];
                for (int e = 0; e < 12; e++) edgeVerts[e] = -1;

                for (int e = 0; e < 12; e++)
                {
                    if ((edgeMask & (1 << e)) == 0) continue;
                    edgeVerts[e] = GetOrAddEdgeVertex(verts, cache, x, y, z, e, W, H, D, invW, invH, invD);
                }

                var triRow = TriangleTable[idx];
                for (int t = 0; t < 16 && triRow[t] != -1; t += 3)
                {
                    int a = edgeVerts[triRow[t]];
                    int b = edgeVerts[triRow[t + 1]];
                    int c = edgeVerts[triRow[t + 2]];
                    if (a < 0 || b < 0 || c < 0) continue;
                    tris.Add(a);
                    tris.Add(b);
                    tris.Add(c);
                }
            }

            var mesh = new Mesh();
            mesh.indexFormat = verts.Count > 65000
                ? UnityEngine.Rendering.IndexFormat.UInt32
                : UnityEngine.Rendering.IndexFormat.UInt16;
            mesh.SetVertices(verts);
            mesh.SetTriangles(tris, 0);
            mesh.RecalculateNormals();
            mesh.RecalculateBounds();
            return mesh;
        }

        static int Index(int x, int y, int z, int W, int H) => z * W * H + y * W + x;

        // For each marching-cubes edge (0..11) we store (cornerA, cornerB).
        // Corner positions are the standard MC layout used by EdgeTable / TriangleTable.
        static readonly int[,] EdgeCorners =
        {
            {0,1}, {1,2}, {2,3}, {3,0},
            {4,5}, {5,6}, {6,7}, {7,4},
            {0,4}, {1,5}, {2,6}, {3,7},
        };
        static readonly Vector3[] CornerOffsets =
        {
            new(0,0,0), new(1,0,0), new(1,1,0), new(0,1,0),
            new(0,0,1), new(1,0,1), new(1,1,1), new(0,1,1),
        };

        static int GetOrAddEdgeVertex(List<Vector3> verts, Dictionary<long, int> cache,
                                       int cx, int cy, int cz, int edge,
                                       int W, int H, int D,
                                       float invW, float invH, float invD)
        {
            int a = EdgeCorners[edge, 0];
            int b = EdgeCorners[edge, 1];
            var ca = CornerOffsets[a];
            var cb = CornerOffsets[b];
            // Map edge → owning cell coordinate + canonical edge index for caching.
            // For a binary field the midpoint is the surface, so we don't need to
            // interpolate; we just put the vertex at (corner_a + corner_b) / 2.
            int ax = cx + (int)ca.x, ay = cy + (int)ca.y, az = cz + (int)ca.z;
            int bx = cx + (int)cb.x, by = cy + (int)cb.y, bz = cz + (int)cb.z;
            int minX = Mathf.Min(ax, bx), minY = Mathf.Min(ay, by), minZ = Mathf.Min(az, bz);
            // Edge orientation: 0=X-edge (varies in X), 1=Y-edge, 2=Z-edge
            int axis = (ax != bx) ? 0 : (ay != by ? 1 : 2);
            long key = ((long)minZ * H + minY) * W * 3 + (long)minX * 3 + axis;

            if (cache.TryGetValue(key, out var hit)) return hit;

            float mx = (ax + bx) * 0.5f, my = (ay + by) * 0.5f, mz = (az + bz) * 0.5f;
            var pos = new Vector3(mx * invW - 0.5f, my * invH - 0.5f, mz * invD - 0.5f);
            int newIdx = verts.Count;
            verts.Add(pos);
            cache[key] = newIdx;
            return newIdx;
        }

